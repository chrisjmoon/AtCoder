int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    // 1 0 0 0 0 0 0
    // ^ least significant bit
    // 0 1 1 1 1 1 1
    // x ^ y ^ z = a
    // x ^ (y + 1) ^ z = (a ^ y) ^ (y + 1)

    int n, q;
    cin >> n >> q;

    int r = 0;
    vector<int> a(n, 0);
    set<int> indices;
    while (q--)
    {
        int query_type;
        cin >> query_type;

        if (query_type == 1)
        {
            int x;
            cin >> x;
            x--;

            r = (r ^ a[x]) ^ (a[x] + 1);

            if (a[x] == 0)
            {
                indices.insert(x);
            }
            a[x]++;
        }
        else
        {

            for (auto it = indices.begin(); it != indices.end();)
            {
                auto idx = *it;
                r = (r ^ a[idx]) ^ (a[idx] - 1);
                if (a[idx] == 1)
                {
                    it = indices.erase(it);
                }
                else
                {
                    it++;
                }
                a[idx]--;
            }
        }

        cout << r << endl;
    }
}
